/**
 * Третя картинка уроку 4.6 — «Той самий документ у двох режимах»: реальний
 * Word-документ, знятий у двох станах — чистий і з увімкненим записом
 * виправлень та приміткою — потім складений в один кадр поруч.
 *
 * Чистий кадр знімається ДО ввімкнення track changes: перемикання
 * «Без виправлень» ↔ «Усі виправлення» на живому документі з приміткою дає
 * баг рендеру Word (перевірено дослідом кілька разів — лишається кадр із
 * вирваним шматком тексту посеред рядка, не лікується ні зміною масштабу,
 * ні прокруткою геть і назад). Простіше й надійніше — два окремі документи.
 *
 *   node record/_prep-4-6-image3.mjs
 */
import { join } from 'node:path';
import { OUT_DIR, ensureDir } from '../lib/paths.mjs';
import { openMouse } from '../lib/mouse.mjs';
import { bringToFront } from '../lib/stage.mjs';
import { closeWord, commentInWord, newWordDoc, selectInWord, trackChangesOn } from '../lib/word.mjs';
import { grabFrame } from '../lib/screen.mjs';
import { sleep } from '../lib/human.mjs';

const OUT = ensureDir(join(OUT_DIR, '4-6-image3'));
const mouse = openMouse();

const HEAD = 'ПОЛОЖЕННЯ про порядок розгляду звернень громадян (витяг)';
const P41 = '4.1. Відповідь надається в письмовій формі за підписом керівника структурного підрозділу.';

async function makeDoc(body) {
  await newWordDoc();
  await bringToFront('Document');
  await sleep(600);
  await mouse.type(body, { cps: 40 });
  await sleep(400);
}

// ── Кадр 1. Чистий документ — фінальний текст, без жодних слідів правки ───
await makeDoc(`${HEAD}\n\n3.5. Строк розгляду звернення становить 3 робочих дні, за потреби продовжується керівником до 7 робочих днів.\n${P41}`);
await grabFrame(join(OUT, 'bez-vypravlen.png'));
console.log('Знято: без виправлень');
await closeWord();
await sleep(500);

// ── Кадр 2. Той самий документ, зі стартовою (старою) цифрою, запис
//    виправлень і примітка колеги на полях.
//
//    Порядок дій навмисно інакший, ніж здається природним: спершу лише
//    заголовок і примітка НА НЬОМУ (бічна панель приміток з'являється
//    ЗАРАЗ, поки абзаців іще нема), і лише ПОТІМ друкується решта тексту —
//    вже в остаточній, вужчій ширині сторінки. Перевірено дослідом (сім
//    спроб): якщо спершу надрукувати повний текст, а бічну панель викликати
//    ПІЗНІШЕ, Word ламає перемальовування рядка, що переносився, — губить
//    шматок тексту посеред речення, і жодна пауза чи примусова прокрутка
//    цього не лікує. Коли ширина сторінки не змінюється вже ПІСЛЯ того, як
//    рядок склався, бага немає.
await newWordDoc();
await bringToFront('Document');
await sleep(600);
await mouse.type(HEAD, { cps: 40 });
await sleep(400);

// Примітка (без запису виправлень — це незалежна дія) викликає бічну
// панель ЗАРАЗ, поки решти абзаців іще нема. Track changes вмикаємо
// тільки ПІЗНІШЕ, перед самою правкою: інакше ввесь щойно надрукований
// текст піде як одна суцільна вставка, і саму правку («5»→«3») не буде
// видно окремим закресленням.
await commentInWord(HEAD, 'Узгоджено на нараді 14.08 — скорочуємо строк розгляду.');
await sleep(800);

await mouse.type(`\n\n3.5. Строк розгляду звернення становить 5 робочих днів, за потреби продовжується керівником до 10 робочих днів.\n${P41}`, { cps: 40 });
await sleep(500);

await trackChangesOn();
await sleep(300);
await selectInWord(mouse, '5 робочих днів', '5 робочих днів');
await sleep(400);
await mouse.type('3 робочих дні', { cps: 20 });
await sleep(800);

await grabFrame(join(OUT, 'usi-vypravlennya.png'));
console.log('Знято: усі виправлення');

await sleep(300);
await closeWord();
console.log(`Готово: ${OUT}`);
