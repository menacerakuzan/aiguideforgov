/**
 * Реквізити дефектного акта — у трьох варіантах, і це не примха.
 *
 * Помічник щоразу вписує позначку в різне оточення: то «складено дефектний
 * акт № [НОМЕР АКТА]», то «складено дефектний акт від [НОМЕР АКТА]», то без
 * жодного прийменника. Одне-єдине значення в усі три випадки не лягає: на
 * першому дублі вийшло «акт № № 214/03-15», на другому — «акт від 214/03-15
 * від 24 вересня», обидва рази з мовною помилкою просто в кадрі.
 *
 * Тому підставляємо не «значення», а те, що граматично стає на місце
 * позначки, — див. `akRequisites()`.
 */
const AKT = {
  /** Після «№»: «...акт № 214/03-15 від 24.09.2026». */
  afterNumber: '214/03-15 від 24.09.2026',
  /** Після «від»: «...акт від 24.09.2026 № 214/03-15». */
  afterFrom: '24.09.2026 № 214/03-15',
  /** Без прийменника: «...акт № 214/03-15 від 24.09.2026». */
  bare: '№ 214/03-15 від 24.09.2026',
};

/**
 * Що саме друкувати замість позначки, дивлячись на текст ПЕРЕД нею.
 *
 * @param before хвіст речення до позначки (досить останніх символів 30)
 */
export function aktRequisites(before) {
  const tail = before.slice(-30).toLowerCase();
  if (/№\s*$/.test(tail)) return AKT.afterNumber;
  // Без : у JavaScript межа слова визначена для латиниці й цифр, і перед
  // кириличним «від» вона не спрацьовує — умова мовчки не виконувалась.
  if (/(^|\s)від\s*$/.test(tail)) return AKT.afterFrom;
  return AKT.bare;
}



/**
 * Прізвища, які звучать в аудіозаписі наради.
 *
 * Потрібні не для краси: розпізнавання мовлення плутає саме прізвища, і
 * перевірка цього місця — головний людський крок задачі 3. На пробі
 * (`record/_probe-1-1-audio.mjs`, 2026-09-04) помічник почув «Гнатюк» як
 * «Игнатюк» — навіть російською «И», якої в українському алфавіті немає.
 */
export const PRIZVYSHCHA = ['Данилюк', 'Кравчук', 'Мельник', 'Ткаченко', 'Гнатюк'];

/** Відстань Левенштейна — скільки правок відділяє одне слово від іншого. */
function distance(a, b) {
  const prev = Array.from({ length: b.length + 1 }, (_, i) => i);
  for (let i = 1; i <= a.length; i++) {
    let diag = prev[0];
    prev[0] = i;
    for (let j = 1; j <= b.length; j++) {
      const tmp = prev[j];
      prev[j] = Math.min(
        prev[j] + 1,
        prev[j - 1] + 1,
        diag + (a[i - 1] === b[j - 1] ? 0 : 1),
      );
      diag = tmp;
    }
  }
  return prev[b.length];
}

/**
 * Знайти в протоколі спотворене прізвище.
 *
 * Вгадувати наперед не можна: помічник щоразу чує запис трохи інакше, і
 * зашити в сценарій конкретну пару «Игнатюк → Гнатюк» означало б зняти
 * виправлення помилки, якої цього разу могло й не бути. Тому шукаємо чесно:
 *
 *   1. беремо прізвище, основи якого в тексті НЕМАЄ взагалі;
 *   2. серед слів тексту шукаємо найсхожіше на нього (одна-дві правки);
 *   3. якщо таке є — це воно й є, спотворення.
 *
 * Умова (1) важлива: без неї відмінкові форми («Мельник» / «Мельнику»)
 * рахувались би за помилку. Повертає { wrong, right } або null.
 */
export function findMisheard(reply) {
  const words = [...new Set(reply.match(/[А-ЯІЇЄҐA-ZИ][а-яіїєґa-zи’']{4,}/gu) ?? [])];

  for (const right of PRIZVYSHCHA) {
    // Основа без останніх двох літер покриває відмінкові форми прізвища.
    const stem = right.slice(0, -2);
    if (reply.includes(stem)) continue;

    const near = words
      .map((w) => ({ w, d: distance(w.toLowerCase(), right.toLowerCase()) }))
      .filter((x) => x.d > 0 && x.d <= 2)
      .sort((a, b) => a.d - b.d)[0];

    if (near) return { wrong: near.w, right };
  }
  return null;
}

/**
 * Обрати цифру зі зведення, яку глядач зможе перевірити в документі.
 *
 * Задача 2 продає одну думку: перевірити велике зведення коштує секунди, бо
 * шукається не сенс, а конкретне число. У кадрі службовець відкриває звіт,
 * тисне Ctrl+F і вводить цифру — і вона мусить знайтися. Якщо не знайдеться,
 * ролик покаже провал перевірки рівно там, де обіцяє протилежне.
 *
 * Тому не беремо перше-ліпше число з відповіді, а звіряємо кожне з ДЖЕРЕЛОМ
 * звіту (той самий markdown, з якого зібрано PDF) і повертаємо перше, що
 * справді там є, разом зі справжньою сторінкою — її потім показує оверлей
 * монтажу.
 *
 * Це не підтасовка: ні відповідь, ні документ не міняються. Ми лише обираємо,
 * яку з названих помічником цифр піти перевіряти — як зробив би й службовець,
 * що починає з найпомітнішої.
 *
 * Перевагу віддаємо «вагомим» числам — із комою й розрядами (412,6 · 71 340),
 * а не круглим на кшталт 100 чи 214: у документі на 48 сторінок коротке число
 * трапляється десятки разів, і пошук зупиниться не там, де очікує глядач.
 *
 * Нічого не підтвердилось — повертаємо null, і крок перевірки просто не
 * знімається. Показати перевірку, якої не сталося, гірше, ніж не показати.
 *
 * @param reply  текст відповіді помічника
 * @param source вміст zvit-prohrama-9-misyatsiv.md
 * @returns { value, page, hits } або null
 */
export function pickVerifiedNumber(reply, source) {
  const chunks = source.split(/<!--\s*сторінка\s+(\d+)\s*-->/);
  const pages = new Map();
  for (let i = 1; i < chunks.length; i += 2) pages.set(Number(chunks[i]), norm(chunks[i + 1]));

  const seen = new Set();
  const candidates = [];

  for (const raw of norm(reply).match(/\d[\d ]*(?:,\d+)?/g) ?? []) {
    const value = raw.trim();
    if (seen.has(value)) continue;
    seen.add(value);

    const digits = value.replace(/\D/g, '').length;
    if (digits < 3) continue;

    const on = [...pages.entries()].filter(([, txt]) => txt.includes(value)).map(([p]) => p);
    if (!on.length) continue;

    // Скільки разів число трапляється в усьому документі: пошук у кадрі має
    // привести до одного очевидного місця, а не гортати десяток збігів.
    const hits = [...pages.values()].reduce((n, txt) => n + txt.split(value).length - 1, 0);
    candidates.push({ value, page: on[0], hits, weight: (value.includes(',') ? 2 : 0) + digits });
  }

  if (!candidates.length) return null;
  candidates.sort((a, b) => a.hits - b.hits || b.weight - a.weight);
  const best = candidates[0];
  return { value: best.value, page: best.page, hits: best.hits };
}

/** Пробіли всіх сортів — в один, щоб «3 128» і «3\u00a0128» збігались. */
function norm(s) {
  return s.replace(/[\u00a0\u202f\s]+/g, ' ');
}
