/**
 * Розкладка кадру.
 *
 * Перша версія клала субтитр поверх запису — і він затуляв то низ документа
 * Word, то поле вводу чату, то кінець відповіді помічника. Саме там, куди
 * глядач і дивиться.
 *
 * Тому екран піднято вгору й трохи зменшено, а внизу відведено власну смугу
 * під текст. Тепер субтитр не може нічого перекрити: місця не перетинаються.
 * Плата — запис у кадрі на 17 % менший; але текст уроку під відео дублює все
 * те саме, а перекритий інтерфейс не дублює ніщо.
 */

/** Смуга під субтитри: два рядки по 32 px із полями. */
export const CAPTION_BAND = 110;

export const SCREEN = {
  width: 1700,
  height: 956,
  x: (1920 - 1700) / 2,
  y: 10,
};

/** Масштаб запису відносно оригінальних 1920×1080. */
export const SCALE = SCREEN.width / 1920;

/**
 * Тло навколо запису.
 *
 * Темне, а не світле: поруч зі світлим інтерфейсом Gemini й білим аркушем Word
 * світлий фон зливається з кадром і перетягує увагу на себе. Темна рамка,
 * навпаки, притискає погляд до екрана — запис читається як підсвічений.
 *
 * Не чорне: чорний дає жорсткий стик по краю картинки. Беремо глибокий
 * синьо-фіолетовий — родич `--ink` із палітри сайта, тому кадр лишається своїм.
 */
export const STAGE = {
  top: '#1B1836',
  bottom: '#100E1F',
};

/**
 * Точка з кадру запису → точка в готовому ролику.
 * Потрібна рамкам уваги: їхні координати міряні по сирому екрану.
 */
export const onScreen = (x: number, y: number, w: number, h: number) => ({
  x: SCREEN.x + x * SCALE,
  y: SCREEN.y + y * SCALE,
  w: w * SCALE,
  h: h * SCALE,
});
