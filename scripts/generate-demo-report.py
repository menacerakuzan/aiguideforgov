def filler(seed: int, count: int = 3) -> list[str]:
    """Кілька типових абзаців — щоб сторінка мала реальний обсяг, як у справжньому звіті."""
    return [FILLER[(seed * 3 + i) % len(FILLER)] for i in range(count)]


def topic(num: int, title: str, intro: str, items: list[str],
          tbl: tuple[list[str], list[list[str]]], extra: list[str], pages_count: int = 2) -> None:
    """Типовий напрям звіту: 2–3 сторінки однакової будови з різним змістом."""
    f1 = filler(num, 3)
    page(
        f"## {num}. {title}",
        f"{num}.1. {intro}",
        f"{num}.2. Протягом звітного періоду виконано такі роботи:",
        "\n".join(f"- {i};" for i in items[:-1]) + f"\n- {items[-1]}.",
        f"{num}.3. Роботи виконувалися силами комунального підприємства «Міськблагоустрій» "
        f"та підрядними організаціями відповідно до укладених договорів.",
        f"{num}.4. {f1[0]}",
        f"{num}.5. {f1[1]}",
    )
    f2 = filler(num + 3, 3)
    page(
        f"## {num}. {title} (продовження)",
        f"{num}.6. Обсяги виконаних робіт у розрізі місяців наведено в таблиці:",
        table(*tbl),
        *[f"{num}.{7 + i}. {e}" for i, e in enumerate(extra)],
        f"{num}.{7 + len(extra)}. {f2[0]}",
        f"{num}.{8 + len(extra)}. {f2[1]}",
        f"{num}.{9 + len(extra)}. {f2[2]}",
    )
    if pages_count > 2:
        f3 = filler(num + 6, 4)
        page(
            f"## {num}. {title} (продовження)",
            f"{num}.12. За результатами обстежень, проведених спеціалістами відділу, складено "
            f"{7 + num} актів обстеження об'єктів. Виявлені недоліки усунено в робочому порядку.",
            f"{num}.13. Скарг на якість виконаних робіт від мешканців у звітному періоді "
            f"не надходило. Зауваження, висловлені під час особистих прийомів, враховано "
            f"під час планування робіт на наступний період.",
            f"{num}.14. {f3[0]}",
            f"{num}.15. {f3[1]}",
            f"{num}.16. {f3[2]}",
            f"{num}.17. {f3[3]}",
        )


