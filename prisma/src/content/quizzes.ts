/**
 * Підсумкові тести модулів і фінальна атестація курсу «ШІ в публічній службі».
 *
 * Винесено з seed.ts окремим файлом із двох причин. По-перше, питання — це
 * контент, і правити їх треба там само, де лежать уроки, а не посеред коду
 * створення бази. По-друге, це дає `sync-quiz`: оновити тести, не стираючи
 * користувачів і прогрес (seed чистить базу повністю).
 *
 * Правила, за якими написані питання, — `lessons/README.md` §1.15:
 *   1. Правильні відповіді розкидані по позиціях. До 2026-09-03 усі 50 питань
 *      тестів модулів і всі 30 питань атестації мали правильний варіант другим:
 *      курс разом із сертифікатом проходився натисканням другого варіанта.
 *   2. Варіанти приблизно однакової довжини — інакше найдовший рядок і є
 *      підказкою. Пояснення живе в explainCorrect, а не у варіанті.
 *   3. Дистрактор — реальна помилка, яку справді роблять, а не дурниця.
 *   4. Перевіряємо застосування: «ось ситуація — що з неї випливає», а не
 *      «як називається». Питання, на яке можна відповісти не проходивши
 *      модуль, тут не потрібне.
 *   5. Не повторюємо мікроперевірки уроків дослівно: тест модуля перевіряє
 *      те саме, але на іншій ситуації.
 *
 * Механічна перевірка позицій і довжини — `pnpm --filter @proai/db audit-quiz`.
 */

export interface QuizQuestion {
  text: string;
  options: string[];
  correctIndex: number;
  explainCorrect: string;
  explainWrong: string;
  /** Лише для фінальної атестації: питання блоку безпеки з окремим порогом. */
  isSecurity?: boolean;
}

export interface ModuleQuiz {
  moduleSlug: string;
  passScore: number;
  questions: QuizQuestion[];
}

function q(
  text: string,
  options: string[],
  correctIndex: number,
  explainCorrect: string,
  explainWrong: string,
  isSecurity = false,
): QuizQuestion {
  return { text, options, correctIndex, explainCorrect, explainWrong, isSecurity };
}

