import type { LessonBlock } from '@proai/types';
import { tool } from './tool-logos';

/** Урок для seed: мінімальний набір полів, що йдуть у Prisma Lesson.create(). */
export interface SeedLesson {
  slug: string;
  title: string;
  minutes: number;
  kind?: 'LESSON' | 'EXERCISE';
  blocks: LessonBlock[];
}

export function text(html: string): LessonBlock {
  return { type: 'text', html };
}

export function check(
  question: string,
  options: string[],
  correctIndex: number,
  explainCorrect: string,
  explainWrong: string,
): LessonBlock {
  return { type: 'check', question, options, correctIndex, explainCorrect, explainWrong };
}

export function video(url: string, caption?: string): LessonBlock {
  return { type: 'video', url, caption };
}

/** Заглушка відео: описуємо, що буде в ролику, доки його не знято. */
export function videoSoon(note: string, caption?: string, duration?: string): LessonBlock {
  return { type: 'video', note, caption, duration };
}

/** Зображення уроку. Без `src` рендериться заглушка з описом майбутнього кадру. */
export function image(
  alt: string,
  opts: { src?: string; caption?: string; note?: string } = {},
): LessonBlock {
  return { type: 'image', alt, ...opts };
}

/** Тренажер-сортувальник: розкласти фрагменти по категоріях. */
export function sortExercise(
  intro: string,
  buckets: { label: string; tone: 'green' | 'amber' | 'red' | 'blue' }[],
  items: { text: string; bucket: number; why: string }[],
): LessonBlock {
  return { type: 'sort', intro, buckets, items };
}

/** Тренажер-картки: одне твердження за раз, помилкові повертаються в чергу. */
export function pickExercise(
  intro: string,
  options: string[],
  cards: { text: string; answer: number; why: string }[],
): LessonBlock {
  return { type: 'pick', intro, options, cards };
}

/** Конструктор промпту: поля за формулою → зібрана заготовка з кнопкою «Копіювати». */
export function builder(
  intro: string,
  fields: {
    label: string;
    hint: string;
    placeholder: string;
    examples?: string[];
    optional?: boolean;
    suffix?: string;
  }[],
  outro?: string,
): LessonBlock {
  return { type: 'builder', intro, fields, outro };
}

/** Вправа «знайди помилки»: документ із клікабельними фрагментами (помилки + приманки). */
export function spotExercise(
  intro: string,
  docHead: string,
  paragraphs: ({ text: string } | { text: string; flag: true; wrong: boolean; why: string })[][],
): LessonBlock {
  return { type: 'spot', intro, docHead, paragraphs };
}

/** Клікабельний фрагмент для `spotExercise`: справжня помилка або приманка. */
export function flag(text: string, wrong: boolean, why: string) {
  return { text, flag: true as const, wrong, why };
}

/** Файл для завантаження зі сторінки уроку (демо-документ, чек-лист, шаблон). */
export function file(url: string, name: string, note?: string, meta?: string): LessonBlock {
  return { type: 'file', url, name, note, meta };
}

/** Готовий промпт окремим блоком — із кнопкою «Копіювати». */
export function promptBlock(body: string, title?: string, note?: string): LessonBlock {
  return { type: 'prompt', body: body.trim(), title, note };
}

/**
 * Зовнішнє посилання в тексті уроку. Відкривається в новій вкладці, щоб слухач не втрачав
 * місце в уроці. Підпис за замовчуванням — сам домен: людина має бачити, куди йде, і
 * впізнати цю адресу в адресному рядку (див. урок 1.5 про підробки сайтів).
 */
export function link(url: string, label?: string): string {
  const text = label ?? url.replace(/^https?:\/\//, '').replace(/\/$/, '');
  return `<a href="${url}" target="_blank" rel="noopener noreferrer">${text}</a>`;
}

/** Готовий промпт у тілі text-блоку: тёмна моноширинна плашка (.prompt-block). */
export function prompt(body: string): string {
  return `<div class="prompt-block">${body.trim()}</div>`;
}

