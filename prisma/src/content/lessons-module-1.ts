import type { LessonBlock } from '@yasno/types';
import { tool } from './tool-logos';

/** Урок для seed: мінімальний набір полів, що йдуть у Prisma Lesson.create(). */
export interface SeedLesson {
  slug: string;
  title: string;
  minutes: number;
  kind?: 'LESSON' | 'EXERCISE';
  blocks: LessonBlock[];
}

export function text(html: string): LessonBlock {
  return { type: 'text', html };
}

export function check(
  question: string,
  options: string[],
  correctIndex: number,
  explainCorrect: string,
  explainWrong: string,
): LessonBlock {
  return { type: 'check', question, options, correctIndex, explainCorrect, explainWrong };
}

export function video(url: string, caption?: string): LessonBlock {
  return { type: 'video', url, caption };
}

/** Готовий промпт у тілі text-блоку: тёмна моноширинна плашка (.prompt-block). */
export function prompt(body: string): string {
  return `<div class="prompt-block">${body.trim()}</div>`;
}

