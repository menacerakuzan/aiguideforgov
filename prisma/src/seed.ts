function lessonCreateData(lessons: SeedLesson[]) {
  return lessons.map((l, idx) => ({
    slug: l.slug,
    title: l.title,
    minutes: l.minutes,
    order: idx + 1,
    kind: l.kind ?? 'LESSON',
    content: blocks(l.blocks),
  }));
}

